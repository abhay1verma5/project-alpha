class Command(BaseCommand):
    help = "Seed database with sample government jobs data"

    def handle(self, *args, **options):
        created = 0
        updated = 0
        for job_data in SEED_JOBS:
            job_data = dict(job_data)  # don't mutate original
            title = job_data.pop("title")
            content_type = job_data.pop("content_type", "job")
            slug = slugify(title)[:550]

            existing = Job.objects.filter(slug=slug).first()
            if existing:
                # Update fee and vacancy_details if newly provided
                changed = False
                if "fee" in job_data and job_data["fee"] and not existing.fee:
                    existing.fee = job_data["fee"]
                    changed = True
                if "vacancy_details" in job_data and job_data["vacancy_details"] and not existing.vacancy_details:
                    existing.vacancy_details = job_data["vacancy_details"]
                    changed = True
                if changed:
                    existing.save(update_fields=["fee", "vacancy_details"])
                    updated += 1
                    self.stdout.write(self.style.WARNING(f"  Updated: {title}"))
                else:
                    self.stdout.write(f"  Skip (exists): {title}")
                continue

            Job.objects.create(
                title=title,
                slug=slug,
                content_type=content_type,
                **job_data,
            )
            created += 1
            self.stdout.write(self.style.SUCCESS(f"  Created: {title}"))

        self.stdout.write(self.style.SUCCESS(f"\nSeeded {created} new, updated {updated} existing."))
