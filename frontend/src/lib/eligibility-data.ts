/**
 * Check eligibility against static data.
 * Returns list of exams with eligibility status.
 */
export function checkStaticEligibility(profile: {
  age: number;
  qualification: string;
  category: string;
  gender: string;
}): { exam: ExamEligibility; eligible: boolean; reason?: string }[] {
  return EXAM_DATA.map((exam) => {
    let maxAge = exam.max_age;
    if (profile.category === 'OBC') maxAge += exam.obc_relaxation;
    if (profile.category === 'SC' || profile.category === 'ST') maxAge += exam.sc_st_relaxation;
    if (profile.gender === 'Female') maxAge += exam.female_relaxation;

    const ageEligible = profile.age >= exam.min_age && profile.age <= maxAge;
    const qualEligible = exam.qualifications.includes(profile.qualification);

    if (!ageEligible && !qualEligible) {
      return { exam, eligible: false, reason: 'Age and qualification do not match' };
    }
    if (!ageEligible) {
      return { exam, eligible: false, reason: `Age limit: ${exam.min_age}-${maxAge} years` };
    }
    if (!qualEligible) {
      return { exam, eligible: false, reason: `Minimum: ${exam.min_qualification}` };
    }
    return { exam, eligible: true };
  });
}
